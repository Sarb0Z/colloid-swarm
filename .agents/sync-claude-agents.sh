#!/usr/bin/env bash
# Sync Claude agent definitions from .agents/config.json
#
# Reads model routing from .agents/config.json and regenerates
# .claude/agents/*.md with the correct frontmatter. The agent body is taken
# from .agents/researcher.md (meta blockquotes stripped).
#
# Usage:
#   .agents/sync-claude-agents.sh
#
# Do not hand-edit files in .claude/agents/ — they are generated.
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
config="$repo/.agents/config.json"
agents_dir="$repo/.claude/agents"
researcher_md="$repo/.agents/researcher.md"

mkdir -p "$agents_dir"

python3 - "$config" "$agents_dir" "$researcher_md" <<'PY'
import json, os, sys

config_path, agents_dir, researcher_md = sys.argv[1:]

with open(config_path, encoding="utf-8") as f:
    cfg = json.load(f)

model = cfg.get("models", {}).get("researcher")
model_line = f"model: {model}" if model else ""

# Read researcher.md and strip orchestrator meta blockquotes.
# Blockquotes before the first ## heading are instructions for the orchestrator;
# blockquotes after that are contract examples for the agent.
with open(researcher_md, encoding="utf-8") as f:
    lines = f.readlines()

body_lines = []
seen_heading = False
for line in lines:
    if line.startswith("## "):
        seen_heading = True
    if not seen_heading and (line.startswith("> ") or line.strip() == ">"):
        continue
    body_lines.append(line)

body = "".join(body_lines).strip()

frontmatter_parts = [
    "---",
    "name: researcher",
    "description: Delegate research tasks that turn on current or external facts — library APIs, version compatibility, best practices, security implications, anything load-bearing where a wrong answer changes shipped code. Invoked via Task(subagent_type='researcher', prompt='[genome stamp] + [research question]').",
]
if model_line:
    frontmatter_parts.append(model_line)
frontmatter_parts.append("---")
frontmatter = "\n".join(frontmatter_parts)

header = (
    "<!-- GENERATED by .agents/sync-claude-agents.sh — do not hand-edit. "
    "Edit .agents/config.json and run the sync script. -->\n"
)

output = header + frontmatter + "\n\n" + body + "\n"

out_path = os.path.join(agents_dir, "researcher.md")
with open(out_path, "w", encoding="utf-8") as f:
    f.write(output)

print("generated " + out_path + (f" (model: {model})" if model else " (no model override)"))
PY
